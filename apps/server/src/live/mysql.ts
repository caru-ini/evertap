const EXACT_NUMBER_TYPES = new Set([
  "tinyint",
  "smallint",
  "mediumint",
  "int",
  "bigint",
  "decimal",
]);
const BINARY_TYPES = new Set(["binary", "varbinary", "tinyblob", "blob", "mediumblob", "longblob"]);
/** Read as MySQL prints them, so they show exactly and can be written back as they are. */
const TEXT_READ_TYPES = new Set(["date", "datetime", "timestamp", "json"]);

/** A placeholder and its value for one column; `compare` is for WHERE, not assignment. */
const param = (column: ColumnInfo, value: string | null, compare: boolean) => {
  if (value === null) {
    return { sql: "?", value };
  }
  // Binary cells are shown as 0x…, so that is what comes back when one is edited or filtered on.
  if (BINARY_TYPES.has(column.dataType) && /^0x[\da-f]*$/i.test(value)) {
    return { sql: "UNHEX(?)", value: value.slice(2) };
  }
  if (column.dataType === "bit") {
    return { sql: "CAST(? AS UNSIGNED)", value };
  }
  // A string compared with an integer goes through a double; ids past 2^53 would match neighbors.
  if (compare && EXACT_NUMBER_TYPES.has(column.dataType)) {
    return { sql: "CAST(? AS DECIMAL(65,30))", value };
  }
  return { sql: "?", value };
};

const selectExpression = (column: ColumnInfo) => {
  if (TEXT_READ_TYPES.has(column.dataType)) {
    return `CAST(${quote(column.name)} AS CHAR)`;
  }
  if (column.dataType === "bit") {
    return `${quote(column.name)} + 0`;
  }
  return quote(column.name);
};

const keyText = (value: Cell) => {
  if (value === null) {
    throw new DataError(MISSING_ROW);
  }
  if (typeof value === "boolean") {
    return value ? "1" : "0";
  }
  return String(value);
};

