const credentials = (resource: Database) => {
  const url = new URL(resource.connectionUrl);
  return {
    username: decodeURIComponent(url.username),
    password: decodeURIComponent(url.password),
  };
};

const connect = (options: {
  port: number;
  username: string;
  password: string;
  database?: string;
  /** Instances only: without TLS their caching_sha2_password login wants an RSA key exchange. */
  tls: boolean;
  max: number;
}) =>
  new SQL({
    adapter: "mysql",
    hostname: "127.0.0.1",
    port: options.port,
    username: options.username,
    password: options.password,
    database: options.database,
    tls: options.tls ? "require" : false,
    max: options.max,
    idleTimeout: 60,
  });

/**
 * Retries `attempt` until the service answers; MySQL's first start spends a while initializing.
 * Each try opens a session of its own.
 */
const waitUntilReady = async (attempt: () => Promise<unknown>, name: string) => {
  const deadline = Date.now() + READY_TIMEOUT_MS;
  for (;;) {
    try {
      await attempt();
      return;
    } catch (error) {
      if (Date.now() > deadline) {
        throw new Error(`${name} did not become ready`, { cause: error });
      }
      await Bun.sleep(1000);
    }
  }
};

// Server errors about evertap's own session rather than the statement: out of memory, too many
// connections, failed login, unknown database, shutdown, lost or killed connections. Their messages
// can name evertap's users and hosts, so they stay faults.
const FAULT_ERRNOS = new Set([
  1037, 1038, 1040, 1041, 1043, 1045, 1049, 1053, 1077, 1078, 1079, 1080, 1129, 1130, 1152, 1158,
  1159, 1160, 1161, 1184, 1203, 1927, 3169,
]);

/** Errors the server raised about the statement (client-side errors are 2000 and up). */
const isServerError = (error: unknown): error is InstanceType<typeof SQL.MySQLError> =>
  error instanceof SQL.MySQLError &&
  error.errno !== undefined &&
  error.errno < 2000 &&
  !FAULT_ERRNOS.has(error.errno);

const isUnknownDatabase = (error: unknown): error is InstanceType<typeof SQL.MySQLError> =>
  error instanceof SQL.MySQLError && error.errno === 1049;

/** The resource's own database is gone: its user holds every privilege, so an app may drop it. */
const missingDatabase = (database: string, cause: unknown) =>
  new DataError(
    `Create database ${database} again, as your framework's db:create does, then reload`,
    { cause },
  );

const passServerErrors = async <T>(run: () => Promise<T>) => {
  try {
    return await run();
  } catch (error) {
    if (isServerError(error)) {
      throw new DataError(error.message, { cause: error });
    }
    throw error;
  }
};

/** Runs one change of a batch; a failure says which change it was. */
const change = async <T>(label: string, run: () => Promise<T>) => {
  try {
    return await passServerErrors(run);
  } catch (error) {
    if (error instanceof DataError) {
      throw new DataError(`${label}: ${error.message}`, { cause: error });
    }
    throw error;
  }
};

/** `id=5`, or `a=1, b=x` for a composite key; long values are cut so the message stays short. */
const keyLabel = (key: RowKey) =>
  Object.entries(key)
    .map(([name, value]) => {
      const text = String(value);
      return `${name}=${text.length > 30 ? `${text.slice(0, 30)}…` : text}`;
    })
    .join(", ");

const formatDate = (value: Date) =>
  value
    .toISOString()
    .replace("T", " ")
    .replace("Z", "")
    .replace(/\.000$/, "");

const toCell = (value: unknown): Cell => {
  if (value === null || value === undefined) {
    return null;
  }
  if (typeof value === "string" || typeof value === "boolean") {
    return value;
  }
  if (typeof value === "number") {
    return Number.isFinite(value) ? value : String(value);
  }
  if (typeof value === "bigint") {
    return Number.isSafeInteger(Number(value)) ? Number(value) : value.toString();
  }
  if (value instanceof Date) {
    // Zero dates such as 0000-00-00 have no Date.
    return Number.isNaN(value.getTime()) ? null : formatDate(value);
  }
  if (value instanceof Uint8Array) {
    return `0x${Buffer.from(value).toString("hex")}`;
  }
  return JSON.stringify(value);
};

