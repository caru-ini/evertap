/** Runs every step even when one fails, so a failed provision leaves as little as possible. */
const cleanUp = async (what: string, steps: (() => Promise<unknown>)[]) => {
  for (const step of steps) {
    try {
      await step();
    } catch (error) {
      console.error(`cleaning up ${what}:`, error);
    }
  }
};

