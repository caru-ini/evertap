export const createMysqlDriver = (context: DriverContext): SqlDriver => {
  const { docker, metadata, prefix } = context;
  const proxyName = `${prefix}-proxysql`;
  const instanceName = (id: string) => `${prefix}-mysql-${id}`;
  // Each instance's own, so a root password that leaks from one opens no other.
  const rootPassword = (id: string) =>
    createHmac("sha256", metadata.secret("mysql-root")).update(id).digest("hex");

  const mysqlResources = () =>
    metadata
      .listResources()
      .filter((row): row is Database => row.kind === "database" && row.engine === "mysql");

  /** One session for `run`, closed after, so evertap keeps no connection on an instance. */
  const withSession = async <T>(
    options: Omit<Parameters<typeof connect>[0], "max">,
    run: (sql: SQL) => Promise<T>,
  ) => {
    const sql = connect({ ...options, max: 1 });
    try {
      return await run(sql);
    } finally {
      await sql.close();
    }
  };
  /** `login` names whose root password to use: the instance's, or the template's it came from. */
  const asRoot = <T>(port: number, login: string, run: (sql: SQL) => Promise<T>) =>
    withSession({ port, username: "root", password: rootPassword(login), tls: true }, run);

  const spec = (name: string, version: string, volume: string, login: string): ContainerSpec => ({
    name,
    image: instanceImage(version),
    cmd: ["mysqld", ...INSTANCE_OPTIONS],
    // Used only when the data is new: a copied template keeps its own until provision changes it.
    env: { MYSQL_ROOT_PASSWORD: rootPassword(login) },
    ports: { [MYSQL_PORT]: { hostIp: "127.0.0.1", hostPort: 0 } },
    volumes: { [volume]: "/var/lib/mysql" },
    network: "isolated",
  });

  /** Starts the container and waits until root can log in with `login`'s password. */
  const startContainer = async (containerSpec: ContainerSpec, login: string) => {
    const info = await docker.ensureContainer(containerSpec);
    const port = info.ports[MYSQL_PORT];
    if (!port) {
      throw new Error(`${containerSpec.name} has no published port`);
    }
    await waitUntilReady(
      () => asRoot(port, login, (sql) => sql.unsafe("SELECT 1")),
      containerSpec.name,
    );
    return port;
  };

  const startInstance = async (resource: { id: string; version: string }, login: string) => {
    const name = instanceName(resource.id);
    const port = await startContainer(spec(name, resource.version, name, resource.id), login);
    await followPort(resource.id, port);
    return port;
  };

  const starting = new Map<string, Promise<number>>();
  /** Starts the resource's instance if needed and waits until it answers. */
  const ready = (resource: { id: string; version: string }) => {
    let pending = starting.get(resource.id);
    if (!pending) {
      pending = startInstance(resource, resource.id).finally(() => starting.delete(resource.id));
      starting.set(resource.id, pending);
    }
    return pending;
  };

  /** The instance's port as it runs now; Docker may pick a new one when it restarts it. */
  const runningPort = async (id: string) => {
    const info = await docker.inspect(instanceName(id));
    return info?.running ? info.ports[MYSQL_PORT] : undefined;
  };
  const instancePort = async (resource: Database) => {
    const port = await runningPort(resource.id);
    if (port === undefined) {
      return ready(resource);
    }
    await followPort(resource.id, port);
    return port;
  };

  const removeInstance = async (id: string) => {
    await docker.remove(instanceName(id), [instanceName(id)]);
  };

  // Initialized data for each image: a new instance starts from a copy of it, as initializing takes
  // about 13 seconds and copying about 4. Named by the image, so a newer image gets its own.
  const templateVolume = (version: string) =>
    `${prefix}-mysql-template-${createHash("sha256").update(instanceImage(version)).digest("hex").slice(0, 12)}`;

  const buildTemplate = async (version: string) => {
    const name = `${prefix}-mysql-template`;
    const volume = templateVolume(version);
    // One cut short has no mark; it starts over.
    await docker.remove(name, [volume]);
    try {
      await startContainer(spec(name, version, volume, TEMPLATE), TEMPLATE);
      // A clean shutdown, so a copy needs no recovery.
      await docker.stop(name);
    } finally {
      await docker.remove(name);
    }
    await docker.run(`${name}-mark`, instanceImage(version), ["touch", `/data/${TEMPLATE_MARK}`], {
      [volume]: "/data",
    });
  };

  /** Fills the instance's volume from the template, making the template first if needed. */
  const copyTemplate = async (version: string, id: string) => {
    // Without auto.cnf and the .pem files, each copy makes a server UUID, TLS certificates, and RSA
    // keys of its own when it first starts.
    const copy = () =>
      docker.run(
        `${instanceName(id)}-copy`,
        instanceImage(version),
        [
          "sh",
          "-c",
          `test -f /from/${TEMPLATE_MARK} && cp -a /from/. /to/ && rm -f /to/auto.cnf /to/*.pem /to/${TEMPLATE_MARK}`,
        ],
        { [templateVolume(version)]: "/from", [instanceName(id)]: "/to" },
      );
    try {
      await copy();
    } catch {
      await buildTemplate(version);
      await copy();
    }
  };

  /** ProxySQL's hostgroup for each resource, and the port of its instance it routes to. */
  const routes = new Map<string, { hostgroup: number; port?: number }>();

  const addRoute = async (admin: SQL, id: string, password: string, port?: number) => {
    const hostgroup = Math.max(0, ...[...routes.values()].map((route) => route.hostgroup)) + 1;
    routes.set(id, { hostgroup, port });
    if (port !== undefined) {
      await admin.unsafe(serverRow(hostgroup, port));
    }
    // No default schema: a login without a database lands in information_schema, which an app
    // cannot drop, so dropping its own database never locks it out of creating it again.
    await admin.unsafe(
      `INSERT INTO mysql_users (username, password, default_hostgroup) VALUES (${literal(userName(id))}, ${literal(password)}, ${hostgroup})`,
    );
  };

  const removeRoute = async (admin: SQL, id: string) => {
    const route = routes.get(id);
    routes.delete(id);
    await admin.unsafe(`DELETE FROM mysql_users WHERE username = ${literal(userName(id))}`);
    if (route) {
      await admin.unsafe(`DELETE FROM mysql_servers WHERE hostgroup_id = ${route.hostgroup}`);
    }
    await loadRoutes(admin);
  };

  /** Points the resource's route at its instance's port, which Docker changes when it restarts it. */
  const followPort = async (id: string, port: number) => {
    const route = routes.get(id);
    if (!route || route.port === port) {
      return;
    }
    await asAdmin(async (admin) => {
      await admin.unsafe(`DELETE FROM mysql_servers WHERE hostgroup_id = ${route.hostgroup}`);
      await admin.unsafe(serverRow(route.hostgroup, port));
      await loadRoutes(admin);
    });
    // Only once the entry has it, so a failed update is tried again on the next look.
    route.port = port;
  };

  /** Metadata is the source of truth: the entry's servers and users are rewritten from it. */
  const resync = async (admin: SQL, resources: Database[]) => {
    // A client keeps one session on its instance for as long as it stays, so locks, temporary
    // tables and SET hold. ProxySQL resets that session when the client leaves; with no idle
    // sessions kept, it then closes it.
    await admin.unsafe("SET mysql-multiplexing = 'false'");
    await admin.unsafe("SET mysql-free_connections_pct = 0");
    await admin.unsafe("LOAD MYSQL VARIABLES TO RUNTIME");
    await admin.unsafe("SAVE MYSQL VARIABLES TO DISK");
    await admin.unsafe("DELETE FROM mysql_servers");
    await admin.unsafe("DELETE FROM mysql_users");
    routes.clear();
    for (const resource of resources) {
      await addRoute(
        admin,
        resource.id,
        credentials(resource).password,
        await runningPort(resource.id),
      );
    }
    await loadRoutes(admin);
  };

  const adminPassword = () => metadata.secret("proxysql-admin");
  // Only this user can enter the directory, so no one else on this machine can listen in
  // ProxySQL's place or log in to it, as they could at a port on 127.0.0.1.
  const socketDir = join(context.dir, "sockets");
  const adminSocket = join(socketDir, "admin.sock");
  /** One session on ProxySQL's admin socket for `run`, closed after. */
  const withAdmin = async <T>(run: (admin: SQL) => Promise<T>) => {
    const admin = new SQL({
      adapter: "mysql",
      path: adminSocket,
      // Bun's client goes to TCP while the socket is missing, and stays there: this sends it to a
      // port only root can listen on, never to whoever listens on 3306.
      hostname: "127.0.0.1",
      port: 1,
      username: "evertap",
      password: adminPassword(),
      tls: false,
      max: 1,
    });
    try {
      return await run(admin);
    } finally {
      await admin.close();
    }
  };

  let proxyStarted = false;
  let forward: TcpForward | undefined;

  const startProxy = async (resources: Database[]) => {
    const configPath = join(context.dir, "proxysql.cnf");
    await mkdir(socketDir, { recursive: true, mode: 0o700 });
    await chmod(socketDir, 0o700);
    // ProxySQL's PostgreSQL module listens on 0.0.0.0 unless told otherwise; sockets inside its
    // container keep it off this machine's network.
    await Bun.write(configPath, proxyConfig(adminPassword()));
    // On this machine's network, as nothing on the isolated one reaches an instance, and with no
    // TCP listener of its own. A replaced entry starts empty; its servers and users come back from
    // metadata below.
    await docker.ensureContainer({
      name: proxyName,
      image: PROXYSQL_IMAGE,
      // The image's own command, without its call home for the newest version.
      cmd: ["proxysql", "-f", "--idle-threads", "-D", "/var/lib/proxysql", "--no-version-check"],
      network: "host",
      binds: { [configPath]: "/etc/proxysql.cnf", [socketDir]: PROXY_SOCKETS },
    });
    await waitUntilReady(() => withAdmin((admin) => admin.unsafe("SELECT 1")), proxyName);
    await withAdmin((admin) => resync(admin, resources));
    proxyStarted = true;
    forward ??= startTcpForward({
      ...context.entry(),
      target: async () => {
        if (!(await docker.inspect(proxyName))?.running) {
          throw new Error(`${proxyName} is not running`);
        }
        return join(socketDir, "mysql.sock");
      },
    });
  };

  let proxyStarting: Promise<void> | undefined;
  /** `run` on the entry's admin interface, bringing the entry up first if it is not. */
  const asAdmin = async <T>(
    run: (admin: SQL) => Promise<T>,
    resources: Database[] = mysqlResources(),
  ) => {
    // A restarted entry keeps its users on its own disk.
    if (!proxyStarted || proxyStarting || !(await docker.inspect(proxyName))?.running) {
      proxyStarting ??= startProxy(resources).finally(() => {
        proxyStarting = undefined;
      });
      await proxyStarting;
    }
    return withAdmin(run);
  };

  // Browsing connects straight to the instance as the resource's own user, not through the entry,
  // and closes its session after each call.
  const asOwner = async <T>(resource: Database, run: (sql: SQL) => Promise<T>) => {
    const database = userName(resource.id);
    try {
      return await withSession(
        { port: await instancePort(resource), ...credentials(resource), database, tls: true },
        run,
      );
    } catch (error) {
      throw isUnknownDatabase(error) ? missingDatabase(database, error) : error;
    }
  };

  const describe = async (sql: SQL, resource: Database, table: TableRef) => {
    if (table.schema !== userName(resource.id)) {
      throw new DataError(MISSING_TABLE);
    }
    const columns = columnsSchema.parse(
      await sql.unsafe(
        `SELECT c.COLUMN_NAME AS name, c.COLUMN_TYPE AS type, c.DATA_TYPE AS dataType,
           c.IS_NULLABLE AS nullable, c.COLUMN_DEFAULT AS \`default\`, c.EXTRA AS extra,
           k.ORDINAL_POSITION AS keyPosition
         FROM information_schema.COLUMNS c
         LEFT JOIN information_schema.KEY_COLUMN_USAGE k
           ON k.TABLE_SCHEMA = c.TABLE_SCHEMA AND k.TABLE_NAME = c.TABLE_NAME
           AND k.COLUMN_NAME = c.COLUMN_NAME AND k.CONSTRAINT_NAME = 'PRIMARY'
         WHERE c.TABLE_SCHEMA = ? AND c.TABLE_NAME = ?
         ORDER BY c.ORDINAL_POSITION`,
        [table.schema, table.name],
      ),
    );
    if (columns.length === 0) {
      throw new DataError(MISSING_TABLE);
    }
    const key = columns
      .filter((column) => column.keyPosition !== null)
      .toSorted((a, b) => (a.keyPosition ?? 0) - (b.keyPosition ?? 0));
    const byName = new Map(columns.map((column) => [column.name, column]));
    const column = (name: string) => {
      const found = byName.get(name);
      if (!found) {
        throw new DataError(`There is no column ${name}. Reload the rows`);
      }
      return found;
    };
    return { target: `${quote(table.schema)}.${quote(table.name)}`, columns, key, column };
  };

  type Described = Awaited<ReturnType<typeof describe>>;

  /** WHERE for one row by its full primary key. */
  const keyCondition = ({ key }: Described, rowKey: RowKey) => {
    if (key.length === 0) {
      throw new DataError(NO_PRIMARY_KEY);
    }
    const names = Object.keys(rowKey);
    if (names.length !== key.length || key.some((column) => !(column.name in rowKey))) {
      throw new DataError(MISSING_ROW);
    }
    const params = key.map((column) => param(column, keyText(rowKey[column.name] ?? null), true));
    return {
      sql: key
        .map((column, index) => `${quote(column.name)} = ${params[index]?.sql ?? "?"}`)
        .join(" AND "),
      values: params.map((p) => p.value),
    };
  };

  const assignments = (described: Described, values: RowValues) =>
    Object.entries(values).map(([name, value]) => {
      const column = described.column(name);
      return { column, ...param(column, value, false) };
    });

  return {
    images: (version) => [PROXYSQL_IMAGE, instanceImage(version)],

    start: async (resources) => {
      // Statements sent before evertap started are not use.
      await asAdmin((admin) => admin.unsafe(SENT_SINCE_LAST_READ), resources);
      // Templates of images this release no longer runs.
      const current = new Set(DATABASE_VERSIONS.mysql.map(templateVolume));
      const { volumes } = await docker.listByPrefix(prefix);
      for (const volume of volumes) {
        if (volume.startsWith(`${prefix}-mysql-template-`) && !current.has(volume)) {
          await docker.remove(`${prefix}-mysql-template`, [volume]);
        }
      }
      await Promise.all(
        resources.map((resource) =>
          ready(resource).catch((error: unknown) => {
            console.error(`starting ${resource.name}:`, error);
          }),
        ),
      );
    },

    provision: async (input) => {
      // The entry first: without it the new database could not be reached.
      await asAdmin(async () => {});
      const user = userName(input.id);
      try {
        await copyTemplate(input.version, input.id);
        const port = await startInstance(input, TEMPLATE);
        await asRoot(port, TEMPLATE, async (sql) => {
          // Out of the binary log, which the app can read: these carry password hashes.
          await sql.unsafe("SET SESSION sql_log_bin = 0");
          for (const host of ["%", "localhost"]) {
            await sql.unsafe(
              `ALTER USER 'root'@'${host}' IDENTIFIED BY ${literal(rootPassword(input.id))}`,
            );
          }
          await sql.unsafe(
            `CREATE USER ${literal(user)}@'%' IDENTIFIED BY ${literal(input.password)}`,
          );
          await sql.unsafe(`GRANT ALL PRIVILEGES ON *.* TO ${literal(user)}@'%' WITH GRANT OPTION`);
          await sql.unsafe(`CREATE DATABASE ${quote(user)}`);
        });
        await asAdmin(async (admin) => {
          await addRoute(admin, input.id, input.password, port);
          await loadRoutes(admin);
        });
      } catch (error) {
        // Nothing records a resource that failed to provision, so leave no instance behind.
        await cleanUp(input.name, [
          () => asAdmin((admin) => removeRoute(admin, input.id)),
          () => removeInstance(input.id),
        ]);
        throw error;
      }
      return {
        connectionUrl: `mysql://${user}:${input.password}@${context.urlHost}:${context.urlPort}/${user}`,
      };
    },

    drop: async (resource) => {
      await asAdmin((admin) => removeRoute(admin, resource.id));
      await removeInstance(resource.id);
    },

    usage: async (resources) => {
      const sizeBytes = new Map<string, number>();
      for (const resource of resources) {
        const port = await runningPort(resource.id);
        if (port === undefined) {
          continue;
        }
        try {
          await followPort(resource.id, port);
          const [row] = sizeSchema.parse(
            await asRoot(port, resource.id, (sql) =>
              sql.unsafe(
                `SELECT COALESCE(SUM(DATA_LENGTH + INDEX_LENGTH), 0) AS size
                 FROM information_schema.TABLES
                 WHERE TABLE_SCHEMA NOT IN (${SYSTEM_DATABASES.map(() => "?").join(", ")})`,
                SYSTEM_DATABASES,
              ),
            ),
          );
          sizeBytes.set(resource.id, row?.size ?? 0);
        } catch (error) {
          console.error(`usage for ${resource.name}:`, error);
        }
      }
      const { stats, sent } = await asAdmin(async (admin) => ({
        // Client sessions on the entry, as evertap's own go straight to the instances.
        stats: statsSchema.parse(
          await admin.unsafe("SELECT username, frontend_connections FROM stats_mysql_users"),
        ),
        // A session that opened and closed between two looks shows only here. Read last, as
        // reading resets the counts: a look that fails before this leaves them to the next one.
        sent: usernamesSchema.parse(await admin.unsafe(SENT_SINCE_LAST_READ)),
      }));
      const connected = new Set([
        ...stats.filter((row) => row.frontend_connections > 0).map((row) => row.username),
        ...sent.map((row) => row.username),
      ]);
      return new Map<string, Usage>(
        resources.flatMap((row) => {
          const size = sizeBytes.get(row.id);
          return size === undefined
            ? []
            : [[row.id, { sizeBytes: size, connected: connected.has(userName(row.id)) }]];
        }),
      );
    },

    rebind: () => {
      forward?.move(context.entry());
    },

    close: async () => {
      await Promise.allSettled([...starting.values(), proxyStarting]);
      forward?.stop();
      forward = undefined;
      proxyStarted = false;
    },

    listTables: async (resource) => {
      const database = userName(resource.id);
      const rows = await asOwner(resource, (sql) =>
        passServerErrors(async () =>
          tablesSchema.parse(
            await sql.unsafe(
              `SELECT TABLE_NAME AS name, TABLE_TYPE AS type, TABLE_ROWS AS estimate
               FROM information_schema.TABLES
               WHERE TABLE_SCHEMA = ? AND TABLE_TYPE IN ('BASE TABLE', 'VIEW')
               ORDER BY TABLE_NAME`,
              [database],
            ),
          ),
        ),
      );
      return rows.map((row) => ({
        schema: database,
        name: row.name,
        kind: row.type === "VIEW" ? "view" : "table",
        rowEstimate: row.type === "VIEW" ? null : row.estimate,
      }));
    },

    readRows: async (resource, input) =>
      asOwner(resource, (sql) =>
        passServerErrors(async () => {
          const described = await describe(sql, resource, input.table);
          const conditions: string[] = [];
          const values: (string | null)[] = [];
          for (const filter of input.filters) {
            const column = described.column(filter.column);
            const name = quote(column.name);
            if (filter.op === "null" || filter.op === "not-null") {
              conditions.push(`${name} IS ${filter.op === "null" ? "" : "NOT "}NULL`);
            } else if (filter.op === "contains") {
              conditions.push(`CAST(${name} AS CHAR) LIKE ?`);
              values.push(`%${filter.value.replaceAll(/[\\%_]/g, "\\$&")}%`);
            } else {
              const operator = { eq: "=", neq: "<>", lt: "<", gt: ">" }[filter.op];
              const p = param(column, filter.value, true);
              conditions.push(`${name} ${operator} ${p.sql}`);
              values.push(p.value);
            }
          }
          const where = conditions.length > 0 ? ` WHERE ${conditions.join(" AND ")}` : "";
          // The primary key breaks ties so pages do not overlap or skip rows.
          const order = [
            ...(input.sort
              ? [
                  `${quote(described.column(input.sort.column).name)} ${input.sort.direction === "asc" ? "ASC" : "DESC"}`,
                ]
              : []),
            ...described.key.map((column) => quote(column.name)),
          ];
          const orderBy = order.length > 0 ? ` ORDER BY ${order.join(", ")}` : "";
          const rows: unknown[][] = await sql
            .unsafe(
              `SELECT ${described.columns.map(selectExpression).join(", ")} FROM ${described.target}${where}${orderBy} LIMIT ${input.limit} OFFSET ${input.offset}`,
              values,
            )
            .values();
          const [count] = countSchema.parse(
            await sql.unsafe(`SELECT COUNT(*) AS n FROM ${described.target}${where}`, values),
          );
          return {
            columns: described.columns.map((column) => ({
              name: column.name,
              type: column.type,
              nullable: column.nullable === "YES",
              primaryKey: column.keyPosition !== null,
              default: column.extra.includes("auto_increment") ? "auto_increment" : column.default,
            })),
            rows: rows.map((row) => row.map(toCell)),
            total: count?.n ?? 0,
          };
        }),
      ),

    applyChanges: async (resource, table, changes) =>
      asOwner(resource, (sql) =>
        passServerErrors(() =>
          sql.begin(async (tx) => {
            const described = await describe(tx, resource, table);
            if (described.key.length === 0) {
              throw new DataError(NO_PRIMARY_KEY);
            }

            for (const { key, values } of changes.updates) {
              await change(`Update of ${keyLabel(key)}`, async () => {
                const where = keyCondition(described, key);
                const set = assignments(described, values);
                // affectedRows counts only rows whose values changed, so the match is counted first.
                const [count] = countSchema.parse(
                  await tx.unsafe(
                    `SELECT COUNT(*) AS n FROM ${described.target} WHERE ${where.sql} FOR UPDATE`,
                    where.values,
                  ),
                );
                if (count?.n !== 1) {
                  throw new DataError(MISSING_ROW);
                }
                await tx.unsafe(
                  `UPDATE ${described.target} SET ${set
                    .map((s) => `${quote(s.column.name)} = ${s.sql}`)
                    .join(", ")} WHERE ${where.sql}`,
                  [...set.map((s) => s.value), ...where.values],
                );
              });
            }

            let deleted = 0;
            for (const key of changes.deletes) {
              deleted += await change(`Delete of ${keyLabel(key)}`, async () => {
                const where = keyCondition(described, key);
                const result = await tx.unsafe(
                  `DELETE FROM ${described.target} WHERE ${where.sql}`,
                  where.values,
                );
                return z.number().parse(result.affectedRows);
              });
            }

            for (const [index, values] of changes.inserts.entries()) {
              await change(`New row ${index + 1}`, async () => {
                const set = assignments(described, values);
                await tx.unsafe(
                  `INSERT INTO ${described.target} (${set.map((s) => quote(s.column.name)).join(", ")}) VALUES (${set
                    .map((s) => s.sql)
                    .join(", ")})`,
                  set.map((s) => s.value),
                );
              });
            }

            return {
              updated: changes.updates.length,
              deleted,
              inserted: changes.inserts.length,
            };
          }),
        ),
      ),

    runQuery: async (resource, text, options) => {
      const port = await instancePort(resource);
      const database = userName(resource.id);
      // A session per run: SET, an open transaction or LOCK TABLES must not outlive the run.
      const sql = connect({ port, ...credentials(resource), database, tls: true, max: 1 });
      try {
        const opened = await sql.unsafe("SELECT CONNECTION_ID() AS id").catch((error: unknown) => {
          throw isUnknownDatabase(error) ? missingDatabase(database, error) : error;
        });
        const [session] = connectionIdSchema.parse(opened);
        // Only SELECT results are capped this way; one extra row tells that more were dropped.
        await sql.unsafe(`SET SESSION sql_select_limit = ${QUERY_ROWS_MAX + 1}`);
        if (options?.readOnly) {
          await sql.unsafe("SET SESSION TRANSACTION READ ONLY");
        }
        let timedOut = false;
        const timer = setTimeout(() => {
          timedOut = true;
          asRoot(port, resource.id, (root) => root.unsafe(`KILL QUERY ${session?.id ?? 0}`)).catch(
            (error: unknown) => {
              console.error("stopping a MySQL query:", error);
            },
          );
        }, QUERY_TIMEOUT_MS);
        const started = performance.now();
        let results;
        try {
          // Simple (text) protocol: several statements may run; the last one's result is shown.
          results = await sql.unsafe(text).simple();
        } catch (error) {
          if (timedOut) {
            throw new DataError(
              "The statement ran for more than 30 seconds and was stopped. Narrow it down and run it again",
              { cause: error },
            );
          }
          // ER_CANT_EXECUTE_IN_READ_ONLY_TRANSACTION
          if (isServerError(error) && error.errno === 1792) {
            throw new DataError(READ_ONLY_REFUSED, { cause: error });
          }
          // Here an unknown database is one the statement names.
          if (isServerError(error) || isUnknownDatabase(error)) {
            throw new DataError(error.message, { cause: error });
          }
          throw error;
        } finally {
          clearTimeout(timer);
        }
        const durationMs = performance.now() - started;
        const last = Array.isArray(results[0]) ? results.at(-1) : results;
        const rows: Record<string, unknown>[] = [...last];
        const columns = Object.keys(rows[0] ?? {});
        const truncated = rows.length > QUERY_ROWS_MAX;
        const kept = rows.slice(0, QUERY_ROWS_MAX);
        const rowCount: number = rows.length > 0 ? last.count : last.affectedRows;
        return {
          columns,
          rows: kept.map((row) => columns.map((column) => toCell(row[column]))),
          rowCount: truncated ? null : rowCount,
          truncated,
          durationMs,
        };
      } finally {
        await sql.close();
      }
    },
  };
};
